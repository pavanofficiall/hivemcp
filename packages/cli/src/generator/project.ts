import { readFile, readdir, lstat, mkdir, writeFile, rename, unlink, open } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash, randomUUID } from 'node:crypto';
import type { ScanResult } from '../scanner/scan.js';
import type { Capability } from '../capabilities/build.js';
const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';
const digest = (text: string) => createHash('sha256').update(text).digest('hex');
const templateRoot = fileURLToPath(new URL('../../templates/mcp/', import.meta.url));
export async function readPrevious(root: string): Promise<Capability[]> {
  try {
    return JSON.parse(await readFile(path.join(root, '.hive/capabilities.json'), 'utf8'));
  } catch (error: any) {
    if (error.code === 'ENOENT') return [];
    throw new Error(
      'Cannot read previous capabilities.json; preserve it and fix invalid JSON before re-scanning.',
    );
  }
}
async function assertSafe(root: string, relative: string) {
  const parts = relative.split('/');
  if (parts.some((x) => !x || x === '..' || x === '.')) throw new Error('Unsafe generated path');
  let current = root;
  for (const part of parts) {
    current = path.join(current, part);
    try {
      if ((await lstat(current)).isSymbolicLink()) throw new Error(`Refusing symlink: ${current}`);
    } catch (error: any) {
      if (error.code === 'ENOENT') return;
      throw error;
    }
  }
}
export async function generate(result: ScanResult, selected: Capability[]) {
  if (selected.some((c) => !c.supported || !result.candidates.includes(c)))
    throw new Error('Only reviewed, supported scan candidates can be generated.');
  const root = result.application.root;
  await assertSafe(root, '.hive');
  await mkdir(path.join(root, '.hive'), { recursive: true });
  const lock = path.join(root, '.hive/generation.lock');
  const handle = await open(lock, 'wx').catch(() => {
    throw new Error('Another generation is running, or .hive/generation.lock is stale.');
  });
  try {
    const files: Record<string, string> = {};
    async function collect(dir: string, relative = '') {
      for (const entry of await readdir(dir, { withFileTypes: true })) {
        const name = relative + entry.name;
        if (entry.isDirectory()) await collect(path.join(dir, entry.name), name + '/');
        else files['mcp/' + name] = await readFile(path.join(dir, entry.name), 'utf8');
      }
    }
    await collect(templateRoot);
    files['capabilities.json'] = json(result.candidates);
    files['analysis.json'] = json({
      files: result.files,
      schemas: result.schemas,
      services: result.services,
      models: result.models,
      warnings: result.warnings,
    });
    files['manifest.json'] = json({
      version: '0.0.2',
      application: { name: result.application.name, framework: 'nextjs', language: 'typescript' },
      generatedAt: new Date().toISOString(),
      capabilities: selected.map((c) => c.name),
    });
    files['mcp/src/tools.json'] = json(
      selected.map(({ name, description, source, inputSchema, risk }) => ({
        name,
        description,
        source,
        inputSchema,
        risk,
      })),
    );
    files['.gitignore'] = 'mcp/node_modules/\nmcp/dist/\nmcp/.env\ngeneration.lock\n';
    files['mcp/README.md'] =
      `# Hive MCP — ${result.application.name}\n\nGenerated by Hive v0.0.2 from existing Next.js route handlers. Developer-owned source; no business logic is copied.\n\n## Selected tools\n\n${selected.map((c) => `- **${c.name}** — ${c.source.method} ${c.source.route} (${c.risk}); source: ${c.source.file}`).join('\n') || 'No tools selected.'}\n\nInputs use separate path, query, and body objects; inspect src/tools.json for exact schemas and source routes.\n\n## Install and run\n\nStart your application separately. From its root:\n\n\x60\x60\x60sh\nnpm --prefix .hive/mcp install\ncp .hive/mcp/.env.example .hive/mcp/.env\nnpm --prefix .hive/mcp run build\nnpm --prefix .hive/mcp start\n\x60\x60\x60\n\nAlternatively run hive dev after installation. Endpoint: http://127.0.0.1:3333/mcp (Streamable HTTP, stateless). For stdio: npm --prefix .hive/mcp start -- --stdio. Use node dist/server.js directly when a client needs a clean stdio stream; run from .hive/mcp and set environment variables in the client configuration.\n\n## Configuration\n\nHIVE_APP_BASE_URL is the application origin (default http://localhost:3000). HIVE_MCP_PORT defaults to 3333. HIVE_APP_BEARER_TOKEN / HIVE_APP_COOKIE configure existing application credentials. HIVE_FORWARD_AUTH=true opts into incoming Authorization and Cookie forwarding. HIVE_MCP_TOKEN optionally protects this local endpoint; that token is never forwarded to the application. HIVE_HTTP_TIMEOUT_MS defaults to 15000. Do not commit .env or credentials. Authentication remains enforced by your application.\n\n## Inspect and test\n\nConnect any MCP client to the endpoint and use tools/list and tools/call. An MCP inspector can connect in Streamable HTTP mode. Run npm --prefix .hive/mcp test for generated mapping checks. The CLI package integration suite also exercises a real application and SDK client.\n\n## Regenerate\n\nRun hive scan in the application root; review selections again. Hive shows added/changed/removed capabilities. Modified generated files are protected: save your edits outside the generated tree, then restore the original generated file before regenerating. Keep custom extensions in separate, unowned files.\n\n## Limitations\n\nLocal single-user prototype; not production OAuth or a hosted gateway. Only supported REST route handlers and statically resolved Zod inputs are selected. Wrapped handlers, catch-all routes, nested query values, transforms, dynamic schemas and non-JSON bodies require manual review. Permission evidence is heuristic, not an authorization policy. GET risk inference is imperfect: review every selection. Large responses are limited to 2 MB and redirects are refused.\n`;
    await assertSafe(root, '.hive/ownership.json');
    let previous: Record<string, string> = {};
    try {
      previous = JSON.parse(await readFile(path.join(root, '.hive/ownership.json'), 'utf8'));
    } catch (error: any) {
      if (error.code !== 'ENOENT')
        throw new Error('Invalid ownership.json; refusing to overwrite generated files.');
    }
    for (const file of new Set([...Object.keys(files), ...Object.keys(previous)])) {
      await assertSafe(root, '.hive/' + file);
      try {
        const existing = await readFile(path.join(root, '.hive', file), 'utf8');
        if (!previous[file] || digest(existing) !== previous[file])
          throw new Error(
            `Preserving user changes: .hive/${file}. Back up edits and restore the generated version before retrying.`,
          );
      } catch (error: any) {
        if (error.code !== 'ENOENT') throw error;
      }
    }
    for (const [file, content] of Object.entries(files)) {
      const absolute = path.join(root, '.hive', file);
      await mkdir(path.dirname(absolute), { recursive: true });
      const temp = absolute + '.' + randomUUID() + '.tmp';
      await writeFile(temp, content, { flag: 'wx' });
      await rename(temp, absolute);
    }
    for (const file of Object.keys(previous))
      if (!(file in files))
        await unlink(path.join(root, '.hive', file)).catch((error: any) => {
          if (error.code !== 'ENOENT') throw error;
        });
    const ownership = Object.fromEntries(
      Object.entries(files).map(([file, content]) => [file, digest(content)]),
    );
    const ownershipTemp = path.join(root, '.hive/ownership.' + randomUUID() + '.tmp');
    await writeFile(ownershipTemp, json(ownership), { flag: 'wx' });
    await rename(ownershipTemp, path.join(root, '.hive/ownership.json'));
    return { directory: path.join(root, '.hive/mcp'), tools: selected.length };
  } finally {
    await handle.close();
    await unlink(lock);
  }
}
export async function addPackageScript(root: string) {
  await assertSafe(root, 'package.json');
  const file = path.join(root, 'package.json');
  const text = await readFile(file, 'utf8');
  const pkg = JSON.parse(text);
  const command = 'npm --prefix .hive/mcp run dev';
  if (pkg.scripts?.['hive:mcp']) return pkg.scripts['hive:mcp'] === command;
  pkg.scripts = { ...pkg.scripts, 'hive:mcp': command };
  const indent = text.match(/\n([ \t]+)"/)?.[1] ?? '  ';
  await writeFile(file, JSON.stringify(pkg, null, indent) + '\n');
  return true;
}
